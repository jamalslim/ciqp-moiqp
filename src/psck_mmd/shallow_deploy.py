@dataclass
class NoiseModelParams:
    """Generic cost parameters for the depth-versus-width estimate of Sec. VII.

    These are order-of-magnitude figures for a superconducting architecture of
    the 2025/26 era, not measurements of any particular processor. Replace them
    with the calibration of whatever platform is being considered before reading
    the resulting fidelities as anything but a scaling argument."""
    p2q: float = 2.8e-3          # median CZ / fractional-rzz error
    p1q: float = 2.5e-4          # median 1q error
    p_meas: float = 1.2e-2       # median readout assignment error
    t2_us: float = 150.0         # median T2
    ff_latency_us: float = 2.0   # feedforward branch-selection latency
    routing_factor_nonnative: float = 3.0  # SWAP inflation for non-native edges


def _gate_2q_cost(weight: int, fractional_rzz: bool) -> int:
    """Two-qubit-gate cost of one weight-w Z-string rotation, all qubits
    adjacent. w=1: RZ (0). w=2: 1 native rzz/ZZ or 2 CZ. w≥3 without a
    native arbitrary-angle ZZ: CX ladder, 2(w-1) CX + RZ. With a native
    ZZ(θ), available as a fractional two-qubit rotation on some platforms and
    as the MS gate on trapped ions, the ladder
    terminates in one ZZ rotation: CX^{w-2} · ZZ(θ) · CX^{w-2} = 2w-3
    two-qubit gates (identity: CX₁₂ Z₂ CX₁₂ = Z₁Z₂)."""
    if weight <= 1:
        return 0
    if weight == 2:
        return 1 if fractional_rzz else 2
    return (2 * weight - 3) if fractional_rzz else 2 * (weight - 1)


def deployment_budget(gates: list[tuple[int, ...]],
                      n_meas: int,
                      noise: NoiseModelParams,
                      fractional_rzz: bool,
                      native_layout: bool = True,
                      idle_us: float = 0.0,
                      idle_qubits: int = 0,
                      label: str = "") -> dict:
    """Count 2q gates, schedule depth by greedy coloring, and estimate the
    global fidelity F = (1-p2q)^{N2q} (1-p1q)^{N1q} (1-pm)^{n_meas}
                        · exp(-idle_us·idle_qubits/T2).
    `native_layout=False` multiplies N2q by the SWAP routing factor. This is
    an ESTIMATE for triage, not a substitute for transpiling against the
    real backend."""
    weights = [len(g) for g in gates]
    n2q = sum(_gate_2q_cost(w, fractional_rzz) for w in weights)
    if not native_layout:
        n2q = int(round(n2q * noise.routing_factor_nonnative))
    n1q = sum(1 for w in weights if w >= 1)  # one RZ per gate (+ H layers, minor)
    layers = greedy_gate_layers(gates)
    f_gates = (1 - noise.p2q) ** n2q * (1 - noise.p1q) ** n1q
    f_idle = float(np.exp(-idle_us * idle_qubits / noise.t2_us))
    # F_circ: pre-measurement state fidelity under the global-depolarizing
    # surrogate — this is the F that a global-depolarizing fit divides out, and
    # the quantity that decides whether SAMPLES carry the trained structure.
    # Readout is a LOCAL bitflip channel, physically distinct: it attenuates
    # ⟨Z_S⟩ by (1-2ε)^{|S|} and is separately mitigatable (TREX/M3); it is
    # reported apart and must not be folded into the depolarizing F.
    f_meas = (1 - noise.p_meas) ** n_meas
    return {
        "label": label, "n_gates": len(gates), "n_2q": n2q, "n_1q": n1q,
        "sched_layers": len(layers),
        "max_weight": max(weights) if weights else 0,
        "F_gates": f_gates, "F_idle": f_idle,
        "F_circ": f_gates * f_idle,
        "F_readout": f_meas,
        "F_total": f_gates * f_meas * f_idle,
    }


