# Shared: greedy edge/hypergraph coloring → parallel layers
# ═════════════════════════════════════════════════════════════════════════

def greedy_gate_layers(gates: list[tuple[int, ...]]) -> list[list[int]]:
    """Partition gate indices into layers of pairwise-disjoint support
    (greedy first-fit coloring of the gate-intersection graph). For a
    hardware-native heavy-hex pair layer this returns ≤ 4 layers
    (χ'(heavy-hex)=3 plus the single-qubit layer merged where possible)."""
    layers: list[list[int]] = []
    layer_support: list[set[int]] = []
    order = sorted(range(len(gates)), key=lambda j: -len(gates[j]))
    for j in order:
        gj = set(gates[j])
        placed = False
        for li, sup in enumerate(layer_support):
            if not (sup & gj):
                layers[li].append(j)
                sup |= gj
                placed = True
                break
        if not placed:
            layers.append([j])
            layer_support.append(set(gj))
    return layers


