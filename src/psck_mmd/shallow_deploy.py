# RZZ angle canonicalization (fractional gates typically accept θ ∈ [0, π/2] only)
# ═════════════════════════════════════════════════════════════════════════

def fold_rzz(theta: float):
    """RZZ(θ) = pre · RZZ(θ_c) · post up to global phase, θ_c ∈ [0, π/2].
    Identities: X₀-conjugation flips the ZZ sign; RZZ(π) = −i Z⊗Z.
    NUMERICALLY VERIFIED to 7e-16 over 4008 angles incl. all branch
    boundaries and −π/2 (an angle some transpilers reject in
    validate_rzz_pubs on unfolded circuits). Returns
    (theta_c, pre_ops, post_ops) with ops ∈ {("x",0),("z",0),("z",1)},
    to be emitted immediately around the rzz on (q0, q1)."""
    import math
    t = float(theta) % (2 * math.pi)
    if t > math.pi:
        t -= 2 * math.pi
    pre, post = [], []
    if t < 0:
        pre, post, t = pre + [("x", 0)], [("x", 0)] + post, -t
    if t > math.pi / 2:
        pre = pre + [("z", 0), ("z", 1), ("x", 0)]
        post = [("x", 0)] + post
        t = math.pi - t
    return t, pre, post


def _emit_folded_rzz(qc, lam, qa, qb):
    tc, pre, post = fold_rzz(lam)
    qmap = {0: qa, 1: qb}
    for g, q in pre:
        getattr(qc, g)(qmap[q])
    qc.rzz(tc, qa, qb)
    for g, q in post:
        getattr(qc, g)(qmap[q])


def dciqp_reference_marginal(params_list, gates, n_feat, observables, q2g,
                             M: int, seed: int = 424242) -> np.ndarray:
    """Van den Nest reference for what dcIQP produces on the data register:
    the PADDED uniform mixture of component marginals (identical to the
    cIQP data marginal). Used by the audit."""
    padded, _ = _pad_to_power_of_2(params_list)
    active = precompute_active_lists(observables, gates, q2g)
    rng = np.random.default_rng(seed)
    z = np.zeros(len(observables))
    for theta in padded:
        lat = sample_latents(n_feat, M, rng, antithetic=True)
        zl, _ = forward_batch(theta, ParityCache(lat, gates), active)
        z += zl / len(padded)
    return z


