# §2  cat-cIQP compiler + exact dense verifier
# ═════════════════════════════════════════════════════════════════════════

def build_cat_ciqp(params_list: list[np.ndarray],
                   base_gates: list[tuple[int, ...]],
                   n_feat: int,
                   m_copies: int,
                   walsh_support: list[int] | None = None):
    """Compile MoIQP → coherent diagonal on n_feat + a·m_copies qubits with
    GHZ ancilla buses. Ancilla k occupies qubits
        n_feat + k·m_copies + r,   r = 0..m_copies-1  (copies).
    Each compiled gate (j, S) uses copy r_j = j mod m_copies of every
    ancilla in S (round-robin de-congestion; a placement-aware assignment
    would pick the physically nearest copy — same algebra).
    If walsh_support is given, only those S (as bitmask ints) are emitted —
    the deployment object of a Walsh-sparse-trained model.
    Returns (gates, params, info). Prep spec: H+CX-tree (depth ⌈log2 m⌉) or
    constant-depth dynamic GHZ (Bäumer et al.) per ancilla bus; the audit
    simulates the prepared cats directly."""
    padded, a = _pad_to_power_of_2(params_list)
    L_pad = 1 << a
    G = len(base_gates)
    per_gate = np.stack(padded, axis=1)                    # (G, L_pad)
    tilde = np.zeros_like(per_gate)
    for j in range(G):
        tilde[j] = _walsh_hadamard(per_gate[j]) / L_pad

    support = list(range(L_pad)) if walsh_support is None else list(walsh_support)

    def copy_qubit(k: int, r: int) -> int:
        return n_feat + k * m_copies + r

    out_gates: list[tuple[int, ...]] = []
    out_params: list[float] = []
    for j, base in enumerate(base_gates):
        r = j % m_copies
        for S_int in support:
            ang = float(tilde[j, S_int])
            if abs(ang) < 1e-15:
                continue
            anc = tuple(copy_qubit(k, r) for k in range(a) if (S_int >> k) & 1)
            out_gates.append(tuple(sorted(tuple(base) + anc)))
            out_params.append(ang)

    weights = [len(g) for g in out_gates]
    layers = greedy_gate_layers(out_gates)
    info = {
        "n_feat": n_feat, "a": a, "m_copies": m_copies,
        "n_total": n_feat + a * m_copies,
        "n_deploy_gates": len(out_gates),
        "max_weight": max(weights) if weights else 0,
        "sched_layers": len(layers),
        "ghz_prep": {"unitary_depth": int(np.ceil(np.log2(max(m_copies, 1)))),
                     "dynamic_depth": "O(1) w/ feedforward (PRX Quantum 5, 030339)",
                     "cx_per_bus_unitary": m_copies - 1},
    }
    return out_gates, np.asarray(out_params), info


def exact_cat_ciqp_data_marginal(params_list, base_gates, n_feat,
                                 m_copies: int) -> np.ndarray:
    """Dense-statevector data-register distribution of the cat-cIQP circuit
    (small n only; audit tool). Initial state: |+⟩^{n_feat} ⊗ (⊗_k cat_k);
    apply the compiled diagonal; H on data; return marginal over ancillas.
    Convention: qubit q ↔ bit (z >> q) & 1."""
    padded, a = _pad_to_power_of_2(params_list)
    gates_c, params_c, _ = build_cat_ciqp(params_list, base_gates, n_feat,
                                          m_copies)
    N = n_feat + a * m_copies
    dim = 1 << N
    idx = np.arange(dim, dtype=np.uint64)
    bits = ((idx[:, None] >> np.arange(N, dtype=np.uint64)[None, :]) & 1
            ).astype(np.int8)

    # amplitude: data uniform; ancilla bus k must be all-0 or all-1
    amp = np.full(dim, 1.0 / np.sqrt(1 << n_feat), dtype=np.complex128)
    for k in range(a):
        cols = bits[:, n_feat + k * m_copies: n_feat + (k + 1) * m_copies]
        cat_ok = (cols.sum(axis=1) % m_copies == 0) if m_copies > 1 else \
                 np.ones(dim, bool)
        # all-equal test (all zeros or all ones):
        cat_ok = np.all(cols == cols[:, :1], axis=1)
        amp *= np.where(cat_ok, 1.0 / np.sqrt(2.0), 0.0)

    # diagonal phases
    phase = np.zeros(dim)
    for g, th in zip(gates_c, params_c):
        par = bits[:, list(g)].sum(axis=1) % 2
        phase += th * (1.0 - 2.0 * par)
    amp = amp * np.exp(1j * phase)

    # H^{⊗n_feat} on data: ψ'(x, anc) = 2^{-n/2} Σ_z (-1)^{x·z} ψ(z, anc)
    psi = amp.reshape([2] * N, order="F")   # axis q = qubit q
    for q in range(n_feat):
        psi_m = np.moveaxis(psi, q, 0)
        a0, a1 = psi_m[0].copy(), psi_m[1].copy()
        psi_m[0] = (a0 + a1) / np.sqrt(2.0)
        psi_m[1] = (a0 - a1) / np.sqrt(2.0)
        psi = np.moveaxis(psi_m, 0, q)
    prob = np.abs(psi.reshape(dim, order="F")) ** 2
    # marginalize ancillas: sum over ancilla bits
    prob = prob.reshape((1 << n_feat, 1 << (a * m_copies)), order="F").sum(axis=1)
    return prob


def exact_single_iqp_distribution(theta, gates, n: int) -> np.ndarray:
    """Exact p_θ(x) = |(WHT[e^{iφ}])[x]|²/4^n via complex fast WHT (audit)."""
    dim = 1 << n
    idx = np.arange(dim, dtype=np.uint64)
    bits = ((idx[:, None] >> np.arange(n, dtype=np.uint64)[None, :]) & 1
            ).astype(np.int8)
    phase = np.zeros(dim)
    for g, th in zip(gates, theta):
        par = bits[:, list(g)].sum(axis=1) % 2
        phase += th * (1.0 - 2.0 * par)
    v = np.exp(1j * phase)
    h = 1
    while h < dim:
        for i in range(0, dim, 2 * h):
            x, y = v[i:i + h].copy(), v[i + h:i + 2 * h].copy()
            v[i:i + h] = x + y
            v[i + h:i + 2 * h] = x - y
        h *= 2
    return np.abs(v / dim) ** 2


# ═════════════════════════════════════════════════════════════════════════
# §3  Walsh-sparse MoIQP trainer
# ═════════════════════════════════════════════════════════════════════════

def walsh_synthesize(phi: np.ndarray, support: list[int], a: int) -> list[np.ndarray]:
    """θ^{(ℓ)}_j = Σ_{S∈support} (−1)^{ℓ·S} φ_{j,S}.  phi: (|G|, |support|)."""
    L = 1 << a
    thetas = []
    for ell in range(L):
        signs = np.array([1.0 - 2.0 * (bin(ell & S).count("1") % 2)
                          for S in support])
        thetas.append(phi @ signs)
    return thetas


def train_moiqp_walsh_sparse(
    binary: np.ndarray, raw: np.ndarray,
    gates, q2g, D: int, B: int, a: int,
    observables,
    walsh_support: list[int],
    n_epochs: int = 300, mc_batch: int = 2048, lr: float = 0.02,
    eta_psck: float = 5.0, heat_scale: float = 1.0,
    psck_taus=(0.1, 0.3, 0.5, 0.7, 0.9),
    seed: int = 42, grad_clip: float = 10.0, unbiased: bool = True,
    verbose: bool = True,
):
    """PSCK training with the mixture parameterized DIRECTLY in the Walsh
    domain on a restricted support U (∅ must be included). Deployment gate
    count of the coherent cat-cIQP becomes |U|·|G| by construction. Forward
    cost per epoch equals a standard L = 2^a MoIQP epoch; the only addition
    is the Walsh synthesis/analysis chain rule
        dL/dφ_{j,S} = Σ_ℓ (−1)^{ℓ·S} dL/dθ^{(ℓ)}_j .
    Returns (best_phi (|G|,|U|), support, hist)."""
    assert 0 in walsh_support, "support must contain S=∅ (mixture mean)"
    n = D * B
    L = 1 << a
    z_data = z_data_batch(binary, observables)
    iu = np.triu_indices(D, k=1)
    rho_target = np.corrcoef(raw.T)[iu]
    active = precompute_active_lists(observables, gates, q2g)
    omega, Jstar, _, _, _ = build_psck_kernel(
        z_data, observables, D, B, eta=eta_psck, taus=psck_taus,
        heat_scale=heat_scale)

    ng = len(gates)
    U = list(walsh_support)
    rng = np.random.default_rng(seed)
    phi = rng.normal(0, 0.1 / max(1, len(U)) ** 0.5, (ng, len(U)))
    signs_mat = np.array([[1.0 - 2.0 * (bin(ell & S).count("1") % 2)
                           for S in U] for ell in range(L)])   # (L, |U|)
    m_adam = np.zeros_like(phi); v_adam = np.zeros_like(phi)
    rng_mc = np.random.default_rng(seed + 99991)
    best = (np.inf, phi.copy())
    hist = {"loss": [], "z_err": [], "rho_err": []}

    for ep in range(n_epochs):
        thetas = [phi @ signs_mat[ell] for ell in range(L)]
        caches, args_l, zs = [], [], []
        for ell in range(L):
            lat = sample_latents(n, mc_batch, rng_mc, antithetic=True)
            c = ParityCache(lat, gates)
            zl, al = forward_batch(thetas[ell], c, active)
            caches.append(c); args_l.append(al); zs.append(zl)
        z_mix = np.mean(zs, axis=0)

        if unbiased:
            zsB = []
            for ell in range(L):
                lat = sample_latents(n, mc_batch, rng_mc, antithetic=True)
                zl, _ = forward_batch(thetas[ell], ParityCache(lat, gates),
                                      active)
                zsB.append(zl)
            z_mix_B = np.mean(zsB, axis=0)
            loss = psck_mmd2_unbiased(z_mix, z_mix_B, z_data, omega, Jstar,
                                      eta_psck)
            dL_dz = psck_mmd2_unbiased_grad_wrt_za(
                z_mix, z_mix_B, z_data, omega, Jstar, eta_psck)
        else:
            loss, dL_dz = psck_mmd2_and_grad(z_mix, z_data, omega, Jstar,
                                             eta_psck)

        dL_dz_l = dL_dz / L
        g_phi = np.zeros_like(phi)
        for ell in range(L):
            g_theta = backward_batch(thetas[ell], caches[ell], active,
                                     args_l[ell], dL_dz_l)     # (ng,)
            g_phi += np.outer(g_theta, signs_mat[ell])          # chain rule
        gn = float(np.linalg.norm(g_phi))
        if gn > grad_clip:
            g_phi *= grad_clip / gn

        t = ep + 1
        m_adam = 0.9 * m_adam + 0.1 * g_phi
        v_adam = 0.999 * v_adam + 0.001 * g_phi ** 2
        phi -= lr * (m_adam / (1 - 0.9 ** t)) / (
            np.sqrt(v_adam / (1 - 0.999 ** t)) + 1e-8)

        z_err = float(np.mean(np.abs(z_mix - z_data)))
        rho_m, _ = pearson_value_and_jacobian(z_mix, observables, D, B)
        rho_err = float(np.mean(np.abs(rho_m[iu] - rho_target)))
        hist["loss"].append(float(loss)); hist["z_err"].append(z_err)
        hist["rho_err"].append(rho_err)
        if loss < best[0]:
            best = (float(loss), phi.copy())
        if verbose and (ep % 50 == 0 or ep == n_epochs - 1):
            print(f"    [walsh k={len(U)}] ep {ep:4d}  L={loss:.4e}  "
                  f"|Δz|={z_err:.4f}  |Δρ|={rho_err:.4f}")
    return best[1], U, hist


def walsh_sparse_to_components(phi: np.ndarray, support: list[int],
                               a: int) -> list[np.ndarray]:
    """Expand trained Walsh-sparse parameters to L = 2^a component angle
    vectors (for mixture/dcIQP deployment or standard evaluation)."""
    return walsh_synthesize(phi, support, a)
