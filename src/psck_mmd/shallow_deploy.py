"""
psck_mmd.shallow_deploy — Shallow / constant-depth deployment of a trained
MoIQP at constant depth, replacing the depth-catastrophic naive cIQP.

═════════════════════════════════════════════════════════════════════════════
WHY THE NAIVE cIQP IS UNDEPLOYABLE (first principles)
═════════════════════════════════════════════════════════════════════════════
Global-depolarizing fidelity is a GATE-COUNT functional, F ≈ exp(-p2q·N2q);
depth only adds idle decoherence. The naive cIQP has three independent
killers:
  (K1) count:      |G|·2^a compiled gates, weight up to 2+a (CX ladders);
  (K2) congestion: every S≠∅ gate passes through one of only a physical
                   ancilla qubits → depth Ω(|G|·L/a) irrespective of data
                   parallelism;
  (K3) routing:    data↔ancilla and non-native data edges need SWAP chains.
Furthermore, any EXACT COHERENT implementation must physically encode every
nonzero Walsh coefficient φ̃_{j,S} as some gate angle: coherent gate count is
Ω(nnz(φ̃)). Arbitrary-angle diagonals sit outside the Clifford hierarchy, so
gate teleportation cannot compress them (the correction D Z_x D† is another
arbitrary diagonal). The only legitimate levers are therefore:
  (L1) remove the coherent ancillas          →  dcIQP  (this module, §1)
  (L2) shrink nnz(φ̃) at TRAINING time       →  Walsh-sparse MoIQP (§3)
  (L3) de-congest ancillas via GHZ fan-out   →  cat-cIQP (§2)

═════════════════════════════════════════════════════════════════════════════
§1  dcIQP — dynamic-circuit cIQP (EXACT, constant depth, count = 1 component)
═════════════════════════════════════════════════════════════════════════════
The cIQP diagonal commutes with Z-basis measurement of the ancilla register
(it is diagonal on the ancillas). Un-deferring the deferred measurement:

    H^{⊗a} on ancillas → measure ancillas → ℓ ~ Uniform(2^a)
    → feedforward: apply the SINGLE-component circuit U(θ^{(ℓ)}) on data.

The data-register distribution is EXACTLY p_MoIQP (paper Eq. (A15) read
right-to-left; deferred-measurement principle). Ordering matters:
the ancilla measurement + classical feedforward happen while the data qubits
are still in |0⟩, which is an eigenstate of both dephasing and amplitude
damping's fixed point — the feedforward latency is therefore (almost) free.
Cost: dynamic circuits on some platforms exclude fractional rzz, so each
ZZ term costs 2 CZ instead of 1 native rzz.

The classical-per-shot mixture (sample ℓ classically, bind parameters, keep
fractional rzz) is distributionally identical and strictly cheaper; dcIQP's
only additional value is that the mixture index is generated by on-chip
quantum randomness inside one self-contained circuit.

═════════════════════════════════════════════════════════════════════════════
§2  cat-cIQP — coherent constant-depth-in-n via GHZ ancilla buses
═════════════════════════════════════════════════════════════════════════════
Replace each logical ancilla k by an m-qubit GHZ "bus"
    |cat_k⟩ = (|0⟩^{⊗m} + |1⟩^{⊗m})/√2 .
Z on ANY single copy acts as the logical Z̄_k (Z_i|0..0⟩=+|0..0⟩,
Z_i|1..1⟩=−|1..1⟩ for every i). The joint ancilla state
⊗_k |cat_k⟩ = (1/√L) Σ_ℓ |enc(ℓ)⟩ with enc the m-fold repetition encoding,
so every compiled gate exp(i φ̃_{j,S} Z_{G_j} ⊗ Z̄_S) may address the
NEAREST copy of each ancilla in S. This removes killer (K2): with m ~
(parallel gates per layer) copies, all data-disjoint gates run
simultaneously and total depth is O(2^a · a) — constant in n. GHZ buses are
preparable in constant depth with mid-circuit measurement + feedforward
(Bäumer et al., PRX Quantum 5, 030339 (2024)) or depth O(log m) unitarily.
Killer (K1) — gate count — is NOT removed: cat-cIQP remains Ω(nnz(φ̃))
gates. Use it only together with §3. Exactness of the data marginal is
audited to machine precision by dense simulation in audit_shallow_deploy.py.

═════════════════════════════════════════════════════════════════════════════
§3  Walsh-sparse MoIQP — deployment-aware training (original contribution)
═════════════════════════════════════════════════════════════════════════════
Reparameterize the per-component angles in the Walsh domain,
    θ_j^{(ℓ)} = Σ_{S ∈ U} (−1)^{ℓ·S} φ̃_{j,S} ,     U ⊆ 2^{{0..a-1}}, ∅ ∈ U,
and TRAIN φ̃ directly, with a hard support constraint |U| = k ≪ 2^a.
Training cost is unchanged (Van den Nest forward/backward per component;
chain rule dL/dφ̃_{j,S} = Σ_ℓ (−1)^{ℓ·S} dL/dθ_j^{(ℓ)} is one Walsh
synthesis per step). The coherent compiled circuit then has k·|G| gates of
weight ≤ 2 + max_{S∈U}|S| — the information-theoretic optimum is attacked
where it lives, at the encoding size, and the optimizer spends the coherent
budget where the PSCK loss cares. k interpolates between L=1 (U={∅}) and the
full mixture (U = all subsets).

All constructions are exact; nothing in this module is a heuristic
approximation of the trained distribution.
"""
